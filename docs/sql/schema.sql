-- Esquema de la base de datos "banca" (PostgreSQL 16).
-- Equivale al que genera Hibernate a partir de las entidades.

CREATE TABLE clientes (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_identificacion   VARCHAR(20)  NOT NULL
        CONSTRAINT clientes_tipo_identificacion_check CHECK (tipo_identificacion IN ('CC', 'CE', 'PASAPORTE')),
    numero_identificacion VARCHAR(20)  NOT NULL,
    nombres               VARCHAR(100) NOT NULL,
    apellido              VARCHAR(100) NOT NULL,
    correo_electronico    VARCHAR(150) NOT NULL,
    fecha_nacimiento      DATE         NOT NULL,
    fecha_creacion        TIMESTAMP(6) NOT NULL,
    fecha_modificacion    TIMESTAMP(6),
    CONSTRAINT uk_clientes_identificacion UNIQUE (tipo_identificacion, numero_identificacion)
);

CREATE TABLE cuentas (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_cuenta        VARCHAR(20)    NOT NULL
        CONSTRAINT cuentas_tipo_cuenta_check CHECK (tipo_cuenta IN ('AHORROS', 'CORRIENTE')),
    numero_cuenta      VARCHAR(10)    NOT NULL,
    estado             VARCHAR(20)    NOT NULL
        CONSTRAINT cuentas_estado_check CHECK (estado IN ('ACTIVA', 'INACTIVA', 'CANCELADA')),
    saldo              NUMERIC(19, 2) NOT NULL,
    exenta_gmf         BOOLEAN        NOT NULL,
    cliente_id         BIGINT         NOT NULL,
    fecha_creacion     TIMESTAMP(6)   NOT NULL,
    fecha_modificacion TIMESTAMP(6),
    version            BIGINT         NOT NULL,
    CONSTRAINT uk_cuentas_numero UNIQUE (numero_cuenta),
    CONSTRAINT fk_cuentas_cliente FOREIGN KEY (cliente_id) REFERENCES clientes (id)
);

CREATE TABLE movimientos (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_transaccion VARCHAR(36)    NOT NULL,
    cuenta_id          BIGINT         NOT NULL,
    tipo_transaccion   VARCHAR(20)    NOT NULL
        CONSTRAINT movimientos_tipo_transaccion_check CHECK (tipo_transaccion IN ('CONSIGNACION', 'RETIRO', 'TRANSFERENCIA')),
    tipo_movimiento    VARCHAR(10)    NOT NULL
        CONSTRAINT movimientos_tipo_movimiento_check CHECK (tipo_movimiento IN ('CREDITO', 'DEBITO')),
    monto              NUMERIC(19, 2) NOT NULL,
    saldo_resultante   NUMERIC(19, 2) NOT NULL,
    fecha              TIMESTAMP(6)   NOT NULL,
    CONSTRAINT fk_movimientos_cuenta FOREIGN KEY (cuenta_id) REFERENCES cuentas (id)
);

CREATE INDEX idx_movimientos_cuenta_fecha ON movimientos (cuenta_id, fecha);
